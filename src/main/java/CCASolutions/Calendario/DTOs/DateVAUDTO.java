package CCASolutions.Calendario.DTOs;

public class DateVAUDTO {

	private int eclipenoIN;
	private int metonoIN;
	private int year;
	private String month;
	private String week;
	private String day;
	public int getEclipenoIN() {
		return eclipenoIN;
	}
	public void setEclipenoIN(int eclipenoIN) {
		this.eclipenoIN = eclipenoIN;
	}
	public int getMetonoIN() {
		return metonoIN;
	}
	public void setMetonoIN(int metonoIN) {
		this.metonoIN = metonoIN;
	}
	public int getYear() {
		return year;
	}
	public void setYear(int year) {
		this.year = year;
	}
	public String getMonth() {
		return month;
	}
	public void setMonth(String month) {
		this.month = month;
	}
	public String getWeek() {
		return week;
	}
	public void setWeek(String week) {
		this.week = week;
	}
	public String getDay() {
		return day;
	}
	public void setDay(String day) {
		this.day = day;
	}
	
	
}
